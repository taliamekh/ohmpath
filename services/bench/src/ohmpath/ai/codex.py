"""Codex app-server 0.155.0-alpha.16.4 stdio adapter.

Protocol fields are based on the schema generated by this exact CLI version.
No live turn can start until an independent isolation proof is attached by the
coordinator. This module never invokes API-key login, credit reset or fallback.
"""

from __future__ import annotations

import json
import os
import queue
import subprocess
import threading
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol

from .bridge import NarrowToolBridge, TOOLS, ToolDenied

PINNED_CLI_VERSION = "codex-cli 0.155.0-alpha.16.4"
MODEL = "gpt-6-astra"
EFFORT = "medium"
MAX_WIRE_BYTES = 256 * 1024
MAX_EVENTS = 256
MAX_ANSWER_CHARS = 12_000
MIN_REMAINING_PERCENT = 10.0
MCP_SERVER_NAME = "ohmpath_bench"
_FORBIDDEN_ITEMS = frozenset({
    "commandExecution", "fileChange", "webSearch", "browser", "computerUse",
    "imageGeneration",
})


class AdapterError(RuntimeError):
    pass


class ProtocolError(AdapterError):
    pass


class BoundaryUnverified(AdapterError):
    pass


class Transport(Protocol):
    def send(self, message: dict[str, Any]) -> None: ...
    def receive(self, timeout: float) -> dict[str, Any]: ...
    def close(self) -> None: ...


class JsonLineProcess:
    """Supervise one app-server process with bounded newline-delimited JSON."""

    def __init__(self, command: tuple[str, ...] = ("codex", "app-server", "--strict-config")):
        if command != ("codex", "app-server", "--strict-config"):
            raise AdapterError("unexpected_codex_command")
        version = subprocess.run(["codex", "--version"], capture_output=True, text=True, timeout=5, check=True)
        if version.stdout.strip() != PINNED_CLI_VERSION:
            raise AdapterError("codex_version_mismatch")
        env = os.environ.copy()
        # Do not silently change a ChatGPT subscription request into API billing.
        for key in list(env):
            if key.upper() in {"OPENAI_API_KEY", "CODEX_API_KEY", "AZURE_OPENAI_API_KEY"}:
                env.pop(key)
        self._process = subprocess.Popen(
            command, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=False, env=env, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        self._incoming: queue.Queue[dict[str, Any] | BaseException] = queue.Queue(maxsize=MAX_EVENTS + 4)
        threading.Thread(target=self._reader, daemon=True).start()

    def _reader(self) -> None:
        assert self._process.stdout is not None
        try:
            while True:
                line = self._process.stdout.readline(MAX_WIRE_BYTES + 1)
                if not line:
                    raise ProtocolError("app_server_closed")
                if len(line) > MAX_WIRE_BYTES or not line.endswith(b"\n"):
                    raise ProtocolError("overlong_protocol_message")
                value = json.loads(line)
                if not isinstance(value, dict):
                    raise ProtocolError("invalid_protocol_message")
                self._incoming.put_nowait(value)
        except (ValueError, queue.Full, BaseException) as error:
            try:
                self._incoming.put_nowait(error)
            except queue.Full:
                pass
            self.close()

    def send(self, message: dict[str, Any]) -> None:
        wire = json.dumps(message, separators=(",", ":"), ensure_ascii=False).encode("utf-8") + b"\n"
        if len(wire) > MAX_WIRE_BYTES:
            raise ProtocolError("overlong_protocol_request")
        if self._process.poll() is not None or self._process.stdin is None:
            raise ProtocolError("app_server_closed")
        self._process.stdin.write(wire)
        self._process.stdin.flush()

    def receive(self, timeout: float) -> dict[str, Any]:
        try:
            value = self._incoming.get(timeout=timeout)
        except queue.Empty as error:
            raise ProtocolError("app_server_timeout") from error
        if isinstance(value, BaseException):
            raise ProtocolError("invalid_protocol_stream") from value
        return value

    def close(self) -> None:
        if self._process.poll() is None:
            self._process.terminate()
            try:
                self._process.wait(timeout=2)
            except subprocess.TimeoutExpired:
                self._process.kill()


@dataclass(frozen=True)
class AccessStatus:
    auth_mode: str
    model: str
    supports_image: bool
    remaining_percent: float
    allowance_ok: bool


@dataclass(frozen=True)
class IsolationProof:
    """Evidence from a separate runtime sandbox and tool-denial acceptance probe.

    An app-server config snapshot alone cannot prove Windows filesystem or
    command isolation. The coordinator must construct this only after testing
    an isolated runtime and recording the denied actions in a separate review.
    """

    cli_version: str
    isolated_config: bool
    only_bench_mcp: bool
    shell_denied: bool
    filesystem_denied: bool
    browser_denied: bool
    device_denied: bool
    evidence_reference: str

    def valid(self) -> bool:
        return (
            self.cli_version == PINNED_CLI_VERSION
            and all((self.isolated_config, self.only_bench_mcp, self.shell_denied,
                     self.filesystem_denied, self.browser_denied, self.device_denied))
            and bool(self.evidence_reference.strip())
        )


class CodexAdapter:
    def __init__(self, transport: Transport, bridge: NarrowToolBridge, *, isolation_proof: IsolationProof | None = None,
                 tool_surface: str = "mcp"):
        if tool_surface not in ("mcp", "dynamic"):
            raise AdapterError("invalid_tool_surface")
        self.transport = transport
        self.bridge = bridge
        self.isolation_proof = isolation_proof
        self.tool_surface = tool_surface
        self._next_id = 1
        self._pending_events: list[dict[str, Any]] = []
        self._initialized = False
        self._active: tuple[str, str] | None = None

    def _request(self, method: str, params: dict[str, Any] | None = None, timeout: float = 10) -> dict[str, Any]:
        request_id = self._next_id
        self._next_id += 1
        message: dict[str, Any] = {"id": request_id, "method": method}
        if params is not None:
            message["params"] = params
        self.transport.send(message)
        deadline = time.monotonic() + timeout
        while True:
            response = self.transport.receive(max(.001, deadline - time.monotonic()))
            if response.get("id") == request_id:
                if "error" in response or not isinstance(response.get("result"), dict):
                    raise ProtocolError(f"app_server_request_failed:{method}")
                return response["result"]
            if "id" in response and "method" in response:
                if response["method"] == "item/tool/call" and self.tool_surface == "dynamic":
                    self._pending_events.append(response)
                    if len(self._pending_events) > MAX_EVENTS:
                        raise ProtocolError("too_many_protocol_events")
                    continue
                self.transport.send({"id": response["id"], "error": {"code": -32601, "message": "request denied"}})
                raise AdapterError("unexpected_server_request")
            self._pending_events.append(response)
            if len(self._pending_events) > MAX_EVENTS:
                raise ProtocolError("too_many_protocol_events")
            if time.monotonic() >= deadline:
                raise ProtocolError("app_server_timeout")

    def initialize(self) -> None:
        if self._initialized:
            return
        self._request("initialize", {"clientInfo": {
            "name": "ohmpath", "title": "Ohm Path", "version": "0.1.0",
        }, "capabilities": {"experimentalApi": True}})
        self.transport.send({"method": "initialized", "params": {}})
        self._initialized = True

    def inspect_access(self) -> AccessStatus:
        """Read-only checks. No thread or inference turn is created."""
        self.initialize()
        account = self._request("account/read", {"refreshToken": False}).get("account")
        if not isinstance(account, dict) or account.get("type") != "chatgpt":
            raise AdapterError("subscription_auth_unavailable")
        models = self._request("model/list", {"limit": 100, "includeHidden": False}).get("data")
        if not isinstance(models, list):
            raise ProtocolError("invalid_model_list")
        model = next((entry for entry in models if isinstance(entry, dict) and entry.get("model") == MODEL), None)
        if model is None:
            raise AdapterError("model_unavailable")
        effort = model.get("supportedReasoningEfforts")
        if not isinstance(effort, list) or EFFORT not in [x.get("reasoningEffort") for x in effort if isinstance(x, dict)]:
            raise AdapterError("model_effort_unavailable")
        modalities = model.get("inputModalities")
        if not isinstance(modalities, list) or "image" not in modalities:
            raise AdapterError("model_image_unavailable")
        limits = self._request("account/rateLimits/read")
        if limits.get("ordinaryUsageAllowed") is False:
            raise AdapterError("allowance_unavailable")
        buckets = limits.get("rateLimitsByLimitId")
        bucket = buckets.get("codex") if isinstance(buckets, dict) else limits.get("rateLimits")
        if not isinstance(bucket, dict) or bucket.get("rateLimitReachedType"):
            raise AdapterError("allowance_unavailable")
        windows = [bucket.get("primary"), bucket.get("secondary")]
        used = [w.get("usedPercent") for w in windows if isinstance(w, dict)]
        if not used or any(not isinstance(x, (int, float)) or x < 0 or x > 100 for x in used):
            raise AdapterError("allowance_unavailable")
        remaining = 100.0 - max(used)
        return AccessStatus("chatgpt", MODEL, True, remaining, remaining >= MIN_REMAINING_PERCENT)

    def start_thread(self, cwd: Path) -> str:
        if isinstance(self.transport, JsonLineProcess):
            # This launcher intentionally inherits the signed-in home for
            # read-only account checks. Isolation of that home, skills, plugins,
            # built-in commands and unrelated MCP servers is not yet proven.
            raise BoundaryUnverified("live_process_isolation_unverified")
        if self.isolation_proof is None or not self.isolation_proof.valid():
            raise BoundaryUnverified("runtime_permission_boundary_unverified")
        status = self.inspect_access()
        if not status.allowance_ok:
            raise AdapterError("allowance_margin_reached")
        if not cwd.is_absolute() or not cwd.is_dir():
            raise AdapterError("invalid_isolated_cwd")
        params: dict[str, Any] = {
            "model": MODEL, "allowProviderModelFallback": False,
            "cwd": str(cwd), "approvalPolicy": "never", "ephemeral": True,
            "serviceTier": "default", "serviceName": "ohmpath",
        }
        if self.tool_surface == "dynamic":
            params["dynamicTools"] = [
                {"type": "function", "name": tool["name"], "description": tool["description"],
                 "inputSchema": tool["inputSchema"]}
                for tool in self.bridge.advertised_tools()
            ]
        result = self._request("thread/start", params)
        if result.get("model") != MODEL:
            raise AdapterError("model_rerouted")
        thread = result.get("thread")
        thread_id = thread.get("id") if isinstance(thread, dict) else None
        if not isinstance(thread_id, str) or not thread_id:
            raise ProtocolError("invalid_thread_id")
        return thread_id

    def start_turn(self, thread_id: str, text: str, *, image: Path | None = None) -> str:
        if isinstance(self.transport, JsonLineProcess):
            raise BoundaryUnverified("live_process_isolation_unverified")
        if self.isolation_proof is None or not self.isolation_proof.valid():
            raise BoundaryUnverified("runtime_permission_boundary_unverified")
        if self._active is not None:
            raise AdapterError("turn_already_active")
        if not isinstance(text, str) or not text or len(text) > 12_000:
            raise AdapterError("invalid_turn_input")
        status = self.inspect_access()
        if not status.allowance_ok:
            raise AdapterError("allowance_margin_reached")
        inputs: list[dict[str, str]] = [{"type": "text", "text": text}]
        if image is not None:
            if not image.is_absolute() or not image.is_file() or image.stat().st_size > 2_000_000:
                raise AdapterError("invalid_image")
            inputs.append({"type": "localImage", "path": str(image)})
        result = self._request("turn/start", {
            "threadId": thread_id, "input": inputs, "model": MODEL, "effort": EFFORT,
            "serviceTierForTurn": "default", "approvalPolicy": "never",
        })
        turn = result.get("turn")
        turn_id = turn.get("id") if isinstance(turn, dict) else None
        if not isinstance(turn_id, str) or not turn_id:
            raise ProtocolError("invalid_turn_id")
        self._active = (thread_id, turn_id)
        return turn_id

    def cancel(self) -> None:
        if self._active is None:
            return
        thread_id, _ = self._active
        try:
            self._request("turn/interrupt", {"threadId": thread_id}, timeout=3)
        finally:
            self._active = None

    def collect(self, *, expected_circuit_revision: str, allowed_evidence_ids: set[str], timeout: float = 60) -> str:
        if self._active is None:
            raise AdapterError("no_active_turn")
        if not expected_circuit_revision or not allowed_evidence_ids:
            raise AdapterError("missing_answer_validation_context")
        thread_id, turn_id = self._active
        deadline = time.monotonic() + timeout
        seen = 0
        completed_items: list[dict[str, Any]] = []
        try:
            while seen < MAX_EVENTS and time.monotonic() < deadline:
                event = self._pending_events.pop(0) if self._pending_events else self.transport.receive(max(.001, deadline - time.monotonic()))
                seen += 1
                if "id" in event and "method" in event:
                    if event["method"] == "item/tool/call" and self.tool_surface == "dynamic":
                        self._answer_dynamic_tool(event, thread_id, turn_id)
                        continue
                    # Never answer approvals, elicitation, or unexpected requests.
                    self.transport.send({"id": event["id"], "error": {"code": -32601, "message": "request denied"}})
                    raise AdapterError("unexpected_server_request")
                method = event.get("method")
                params = event.get("params")
                if not isinstance(params, dict):
                    continue
                if params.get("threadId") != thread_id:
                    continue
                if method == "item/started" or method == "item/completed":
                    item = params.get("item")
                    if isinstance(item, dict):
                        self._check_item(item)
                        if method == "item/completed" and params.get("turnId") == turn_id:
                            completed_items.append(item)
                if method == "turn/completed":
                    turn = params.get("turn")
                    if not isinstance(turn, dict) or turn.get("id") != turn_id:
                        continue
                    if turn.get("status") != "completed":
                        raise AdapterError("turn_failed_or_interrupted")
                    items = turn.get("items")
                    if not isinstance(items, list) or len(items) > MAX_EVENTS:
                        raise ProtocolError("invalid_turn_items")
                    if not items:
                        items = completed_items
                    for item in items:
                        if not isinstance(item, dict):
                            raise ProtocolError("invalid_turn_items")
                        self._check_item(item)
                    answers = [item.get("text") for item in items
                               if isinstance(item, dict) and item.get("type") == "agentMessage"]
                    if not answers or not isinstance(answers[-1], str) or len(answers[-1]) > MAX_ANSWER_CHARS:
                        raise ProtocolError("invalid_model_output")
                    answer = answers[-1]
                    try:
                        proposal = json.loads(answer)
                    except ValueError as error:
                        raise ProtocolError("invalid_model_output") from error
                    if not isinstance(proposal, dict) or set(proposal) != {
                        "circuit_revision", "explanation", "evidence_ids", "proposed_test_id"
                    }:
                        raise ProtocolError("invalid_model_output")
                    refs = proposal["evidence_ids"]
                    if (proposal["circuit_revision"] != expected_circuit_revision
                            or not isinstance(proposal["explanation"], str)
                            or not proposal["explanation"].strip()
                            or not isinstance(refs, list) or not refs
                            or any(not isinstance(ref, str) or ref not in allowed_evidence_ids for ref in refs)
                            or not isinstance(proposal["proposed_test_id"], str)):
                        raise ProtocolError("stale_or_unlinked_model_output")
                    self._active = None
                    return answer
            raise ProtocolError("turn_timeout_or_event_limit")
        finally:
            if self._active is not None:
                self.cancel()

    def close(self) -> None:
        try:
            self.cancel()
        finally:
            self.transport.close()

    def _check_item(self, item: dict[str, Any]) -> None:
        kind = item.get("type")
        if kind in _FORBIDDEN_ITEMS:
            raise AdapterError("disallowed_model_action")
        if kind == "dynamicToolCall":
            if self.tool_surface != "dynamic" or item.get("tool") not in TOOLS:
                raise AdapterError("disallowed_model_action")
            if item.get("status") in ("failed", "declined") or item.get("success") is False:
                raise AdapterError("tool_failed")
        if kind == "mcpToolCall":
            if self.tool_surface != "mcp":
                raise AdapterError("disallowed_model_action")
            if item.get("server") != MCP_SERVER_NAME or item.get("tool") not in TOOLS:
                raise AdapterError("disallowed_model_action")
            if item.get("status") in ("failed", "declined") or item.get("error"):
                raise AdapterError("tool_failed")

    def _answer_dynamic_tool(self, event: dict[str, Any], thread_id: str, turn_id: str) -> None:
        params = event.get("params")
        if (not isinstance(params, dict) or params.get("threadId") != thread_id
                or params.get("turnId") != turn_id or params.get("tool") not in TOOLS):
            self.transport.send({"id": event["id"], "error": {"code": -32601, "message": "tool denied"}})
            raise AdapterError("disallowed_model_action")
        try:
            result = self.bridge.call(params["tool"], params.get("arguments"))
            response = {"success": True, "contentItems": [
                {"type": "inputText", "text": json.dumps(result, separators=(",", ":"))},
            ]}
        except ToolDenied as error:
            response = {"success": False, "contentItems": [
                {"type": "inputText", "text": str(error)},
            ]}
        self.transport.send({"id": event["id"], "result": response})
